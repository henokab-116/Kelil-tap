(() => {
  'use strict';
  const { api, $, toast, errMsg, fmt, fmtTime, session, nfc } = App;
  const t = I18N.t;

  let user = null;
  let config = {};
  let qrTimer = null;
  let nfcCtrl = null;

  // ---------- helpers ----------
  const showAuthError = (msg) => { const a = $('authAlert'); a.textContent = msg; a.classList.remove('d-none'); };

  function switchAuthTab(tab) {
    const login = tab === 'login';
    $('tabLogin').classList.toggle('active', login);
    $('tabRegister').classList.toggle('active', !login);
    $('loginForm').classList.toggle('d-none', !login);
    $('registerForm').classList.toggle('d-none', login);
    $('authAlert').classList.add('d-none');
  }

  function navigate(screenId) {
    document.querySelectorAll('.screen-view').forEach((el) => el.classList.toggle('active', el.id === screenId));
    document.querySelectorAll('.nav-btn').forEach((el) => el.classList.toggle('active', el.dataset.screen === screenId));
    if (screenId === 'transactionsScreen') loadTransactions();
  }

  function renderUser() {
    $('userName').textContent = user.name;
    $('userBalance').textContent = fmt(user.balance);
    $('cardUid').textContent = user.cardUid;
    $('profileName').textContent = user.name;
    $('profilePhone').textContent = user.phone;
    $('profileEmail').textContent = user.email || '';
    $('cardStatus').textContent = user.hasCard ? t('cardLinked') : t('cardNotLinked');
    $('unlinkBtn').classList.toggle('d-none', !user.hasCard);
    $('topupOpenBtn').classList.toggle('d-none', !config.demo);
  }

  function enterApp() {
    $('authScreen').classList.add('d-none');
    $('appScreens').classList.remove('d-none');
    $('bottomNav').classList.remove('d-none');
    renderUser();
    navigate('homeScreen');
    App.connectSocket(onBalance);
  }

  function logout() {
    session.clear();
    App.disconnectSocket();
    stopNfc();
    user = null;
    $('appScreens').classList.add('d-none');
    $('bottomNav').classList.add('d-none');
    $('authScreen').classList.remove('d-none');
    $('loginForm').reset();
    $('registerForm').reset();
    switchAuthTab('login');
  }
  App.onUnauthorized = logout;

  function onBalance(d) {
    if (!user) return;
    user.balance = d.balance;
    $('userBalance').textContent = fmt(d.balance);
    if (d.delta) toast(`${d.title}: ${d.delta > 0 ? '+' : '-'}${fmt(Math.abs(d.delta))} ETB`, d.delta > 0 ? 'success' : 'info');
    if ($('transactionsScreen').classList.contains('active')) loadTransactions();
  }

  async function finishAuth(d) {
    if (!d.success) return showAuthError(errMsg(d));
    if (d.user.role !== 'passenger') return showAuthError(t('err_WRONG_APP'));
    session.set(d.token);
    user = d.user;
    enterApp();
  }

  // ---------- transactions ----------
  const ICONS = { topup: 'bi-plus-circle-fill', fare: 'bi-bus-front-fill', fare_received: 'bi-cash-coin', withdrawal: 'bi-box-arrow-up', refund: 'bi-arrow-counterclockwise' };

  async function loadTransactions() {
    const d = await api('/api/wallet/transactions');
    const list = $('txList');
    list.replaceChildren();
    if (!d.success || !d.transactions.length) {
      const empty = document.createElement('div');
      empty.className = 'list-group-item text-center text-secondary py-4';
      empty.textContent = d.success ? t('noTx') : errMsg(d);
      list.append(empty);
      return;
    }
    for (const tx of d.transactions) {
      const credit = tx.type === 'credit';
      const row = document.createElement('div');
      row.className = 'list-group-item d-flex justify-content-between align-items-center py-3';
      const left = document.createElement('div');
      const title = document.createElement('div');
      title.className = 'fw-semibold';
      const icon = document.createElement('i');
      icon.className = `bi ${ICONS[tx.kind] || 'bi-circle'} me-2 text-secondary`;
      title.append(icon, document.createTextNode(tx.title));
      const when = document.createElement('div');
      when.className = 'text-secondary small';
      when.textContent = fmtTime(tx.createdAt);
      left.append(title, when);
      const amt = document.createElement('span');
      amt.className = `fw-bold ${credit ? 'text-success' : 'text-danger'}`;
      amt.textContent = `${credit ? '+' : '-'}${fmt(tx.amount)} ETB`;
      row.append(left, amt);
      list.append(row);
    }
  }

  // ---------- QR ----------
  async function loadQr() {
    const d = await api('/api/passenger/qr');
    if (!d.success) { toast(errMsg(d), 'danger'); return; }
    $('qrBox').innerHTML = d.svg; // SVG generated by our own server from a random token
    $('qrToken').textContent = config.demo ? d.token : '';
  }

  // ---------- NFC card linking ----------
  function stopNfc() { if (nfcCtrl) { nfcCtrl.abort(); nfcCtrl = null; } }

  async function linkCard() {
    if (!nfc.supported()) return toast(t('nfcUnsupported'), 'warning');
    stopNfc();
    try {
      toast(t('tapCardNow'), 'info');
      nfcCtrl = await nfc.start(async (serial) => {
        stopNfc();
        const d = await api('/api/passenger/card', { method: 'PUT', body: { serial } });
        if (d.success) { user.hasCard = true; renderUser(); toast(t('cardLinked'), 'success'); }
        else toast(errMsg(d), 'danger');
      }, () => toast(t('err_NFC_READ'), 'danger'));
    } catch (e) {
      toast(`${t('nfcUnsupported')} (${e.message})`, 'danger');
    }
  }

  // ---------- actions ----------
  App.bindActions({
    authTab: (el) => switchAuthTab(el.dataset.tab),
    nav: (el) => navigate(el.dataset.screen),
    logout,
    linkCard,
    unlinkCard: async () => {
      const d = await api('/api/passenger/card', { method: 'DELETE' });
      if (d.success) { user.hasCard = false; renderUser(); } else toast(errMsg(d), 'danger');
    },
    topup: (el) => App.withBusy(el, async () => {
      const d = await api('/api/wallet/topup', { method: 'POST', body: { amount: $('topupAmount').value } });
      if (!d.success) return toast(errMsg(d), 'danger');
      user.balance = d.newBalance;
      renderUser();
      toast(t('topupDone'), 'success');
      bootstrap.Modal.getInstance($('topupModal')).hide();
    })
  });

  // ---------- boot ----------
  document.addEventListener('DOMContentLoaded', async () => {
    I18N.init();
    App.initTheme();
    App.registerSW();

    $('loginForm').addEventListener('submit', async (e) => {
      e.preventDefault();
      const btn = e.submitter;
      await App.withBusy(btn, async () => finishAuth(await api('/api/auth/login', {
        method: 'POST', body: { login: $('loginId').value, password: $('loginPassword').value }
      })));
    });
    $('registerForm').addEventListener('submit', async (e) => {
      e.preventDefault();
      await App.withBusy(e.submitter, async () => finishAuth(await api('/api/auth/register', {
        method: 'POST',
        body: { name: $('regName').value, phone: $('regPhone').value, email: $('regEmail').value, password: $('regPassword').value }
      })));
    });

    const qrModal = $('qrModal');
    qrModal.addEventListener('shown.bs.modal', () => { loadQr(); qrTimer = setInterval(loadQr, 80000); });
    qrModal.addEventListener('hidden.bs.modal', () => { clearInterval(qrTimer); $('qrToken').textContent = ''; });
    document.addEventListener('langchange', () => { if (user) renderUser(); });

    const c = await api('/api/config');
    config = c.success ? c.config : {};

    if (session.token) {
      const d = await api('/api/auth/me'); // never trust cached data: balance may have changed on another device
      if (d.success && d.user.role === 'passenger') { user = d.user; enterApp(); }
      else { if (d.success) showAuthError(t('err_WRONG_APP')); session.clear(); }
    }
  });
})();
